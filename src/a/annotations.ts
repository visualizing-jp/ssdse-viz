import type { Indicator } from "../shared/types.ts";

/** kaisetsu-A-2026 の「データ利用上の留意点」による項目別の注意。 */
export function cautionsFor(ind: Indicator): string[] {
  const out: string[] = [];
  if (/^C2[12]08(3[23])?$/.test(ind.code)) {
    out.push("経済センサスの事業所数・従業者数には、個人経営の農林漁家を含みません（農家数は農林業センサス、第1次産業就業者数は国勢調査を参照）。");
  }
  if (/^E[23]/.test(ind.code)) {
    out.push("小中一貫の義務教育学校は小学校・中学校とは別に集計されています。すべて義務教育学校に移った市区町村では、小学校・中学校の値が0になります。");
  }
  if (ind.rate?.den === "A1101" && ind.year !== "2020") {
    out.push(`人口あたりの分母は2020年国勢調査の総人口です。この項目の年次（${ind.year}年度）とずれています。`);
  }
  return out;
}

